const USED_IDS_STORAGE_KEY = 'jejak_hikmah_used_question_ids_v1';

function shuffleArray<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = arr[i];
    arr[i] = arr[j];
    arr[j] = tmp;
  }
  return arr;
}

function getUsedQuestionIds(): string[] {
  try {
    const raw = localStorage.getItem(USED_IDS_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed.filter((x): x is string => typeof x === 'string') : [];
  } catch {
    return [];
  }
}

function saveUsedQuestionIds(ids: string[]): void {
  try {
    localStorage.setItem(USED_IDS_STORAGE_KEY, JSON.stringify(ids));
  } catch {
    // Ignore storage quota errors cleanly
  }
}

export function resolveDifficultyForPosition(
  mode: DifficultyMode,
  playerPosition: number
): DifficultyLevel {
  if (mode !== 'adaptif') return mode;
  if (playerPosition <= 33) return 'mudah';
  if (playerPosition <= 67) return 'sedang';
  return 'menantang';
}

export function drawShuffledQuestion(
  mode: DifficultyMode,
  playerPosition: number,
  sessionUsedIds: Set<string>
): DrawnQuestion {
  const targetDifficulty = resolveDifficultyForPosition(mode, playerPosition);
  const globalUsed = new Set(getUsedQuestionIds());

  // 1. Try matching target difficulty and never seen globally or in current session
  let pool = QUESTION_BANK.filter(
    (q) =>
      q.difficulty === targetDifficulty &&
      !sessionUsedIds.has(q.id) &&
      !globalUsed.has(q.id)
  );

  // 2. If exhausted globally for that difficulty, reset global memory for that difficulty
  if (pool.length === 0) {
    const difficultyIds = new Set(
      QUESTION_BANK.filter((q) => q.difficulty === targetDifficulty).map((q) => q.id)
    );
    const cleanedGlobal = [...globalUsed].filter((id) => !difficultyIds.has(id));
    saveUsedQuestionIds(cleanedGlobal);

    pool = QUESTION_BANK.filter(
      (q) => q.difficulty === targetDifficulty && !sessionUsedIds.has(q.id)
    );
  }

  // 3. Fallback across all difficulties not yet asked in this session
  if (pool.length === 0) {
    pool = QUESTION_BANK.filter((q) => !sessionUsedIds.has(q.id));
  }

  // 4. Final fallback if all 116 questions were asked in one marathon session
  if (pool.length === 0) {
    sessionUsedIds.clear();
    pool = QUESTION_BANK;
  }

  const picked = shuffleArray(pool)[0];
  sessionUsedIds.add(picked.id);

  const updatedGlobal = getUsedQuestionIds();
  if (!updatedGlobal.includes(picked.id)) {
    updatedGlobal.push(picked.id);
    saveUsedQuestionIds(updatedGlobal);
  }

  // Also shuffle answer options on every draw so kids cannot memorize letter positions
  const indexedOptions = picked.options.map((text, idx) => ({
    text,
    isCorrect: idx === picked.correctIndex,
  }));
  const shuffled = shuffleArray(indexedOptions);

  return {
    ...picked,
    shuffledOptions: shuffled.map((o) => o.text),
    shuffledCorrectIndex: shuffled.findIndex((o) => o.isCorrect),
  };
}
